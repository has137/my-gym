// First run in Arabic at 390 px: readiness, starting point, Today, every My gym screen.
import { open, goto, state, shot, sleep, assert } from './lib.mjs'

const theme = process.argv[2] || 'light'
const { browser, page, errors } = await open({ theme })
await goto(page, '/home')
await sleep(800)
assert(await page.evaluate(() => document.documentElement.dir) === 'rtl', 'page is right to left')
assert(await page.evaluate(() => document.documentElement.lang) === 'ar', 'page language is Arabic')
await shot(page, theme + '-01-readiness')
// seven questions: all no, then the joint one yes
const groups = page.locator('.mg-yn')
const n = await groups.count()
assert(n === 7, 'seven readiness questions')
for (let i = 0; i < n; i++) await groups.nth(i).locator('button').nth(1).click()
await groups.nth(5).locator('button').nth(0).click()
await page.locator('button.mg-big-btn').click()
await sleep(200)
await shot(page, theme + '-02-readiness-result')
await page.locator('button.mg-big-btn').click()
await sleep(200)
const radios = page.locator('[role=radiogroup]')
await radios.nth(0).locator('[role=radio]').nth(1).click()
await radios.nth(1).locator('[role=radio]').nth(0).click()
await radios.nth(2).locator('[role=radio]').nth(1).click()
await shot(page, theme + '-03-baseline')
await page.locator('button.mg-big-btn').click()
await sleep(800)
const s = await state(page)
assert(!!s.mg?.startedAt, 'programme started')
assert(Object.keys(s.mg.routineIds || {}).join() === 'A,B,C,D,E', 'five routines built')
assert(s.rotation?.sequence?.length === 4, 'rotation of four sessions')
assert(s.mg.readiness.advice === 'joint-only', 'readiness advice is joint-only')
assert(s.mg.rungs.pullup === 1 && s.mg.rungs.pushup === 0, 'ladder rungs from the starting point')
await shot(page, theme + '-04-today')
for (const [hash, name] of [['/session/A', '05-session-A'], ['/session/D', '06-session-D'], ['/library', '07-library'], ['/library?tab=lessons', '08-lessons'], ['/lesson/stance', '09-lesson'], ['/progress', '10-progress'], ['/joints', '11-joints'], ['/timer/A/boxing', '12-timer'], ['/settings', '13-settings']]) {
  await goto(page, hash)
  await sleep(600)
  await shot(page, theme + '-' + name)
}
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1)
assert(!overflow, 'no horizontal scroll at 390 px')
console.log('console errors:', errors.length ? errors : 'none')
await browser.close()
